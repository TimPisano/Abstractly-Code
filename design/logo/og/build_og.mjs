// Builds the social preview: design/logo/og/og-image.svg (the vector
// source, committed) and frontend/og-image.png (2400x1260, what pages link
// to). Called by `node design/logo/render_assets.mjs og`.
//
// Look: near-black, thin evenly spaced gold bars like light through fluted
// glass -- hard edges, no blur or bloom -- brightest in the centre and
// fading smoothly to black at the sides (and softly toward top and
// bottom), with the white mark + "Abstractly" lockup centred on top.
// Everything is vector: the bars are <rect>s, the lockup is
// final/abstractly-lockup-white.svg (wordmark already converted to
// outlines by build.py), so the PNG is sharp at any render size.
import fs from 'node:fs';
import path from 'node:path';

// Design space is the OG standard 1200x630; the PNG is rendered at 2x.
const W = 1200;
const H = 630;
const SCALE = 2;

const BG = '#050506';
const BAR_PITCH = 20;        // centre-to-centre, design px (40px in the PNG)
const BAR_WIDTH = 4;         // design px (8px in the PNG): thin, crisp
const BAR_MAX_OPACITY = 0.95; // centre bars; their gold still sits well under white
const FALLOFF = 3.2;         // higher = light concentrated nearer the centre
const WORDMARK_INK_HEIGHT = 120; // top of "b" to bottom of "y", design px
const MARK_HEIGHT = 120;     // mark matches the wordmark, as in the approved layout
const GAP = 36;              // mark to wordmark
// The mark centres on the wordmark's capitals, not its full ink box (the
// "y" descender would pull it low): 15px above ink centre at 120px.
const MARK_RAISE = 15;

// cos^FALLOFF from 1 at the centre to 0 just past the sides: smooth, with
// no visible edge where the light ends.
function intensity(xCentre) {
  const d = Math.min(1, Math.abs(xCentre - W / 2) / (W / 2 + BAR_PITCH));
  return Math.pow(Math.cos((d * Math.PI) / 2), FALLOFF);
}

function bars() {
  const out = [];
  const n = Math.floor(W / 2 / BAR_PITCH) + 1;
  for (let k = -n; k <= n; k++) {
    const cx = W / 2 + k * BAR_PITCH;
    const x = cx - BAR_WIDTH / 2;
    if (x + BAR_WIDTH < 0 || x > W) continue;
    const o = +(BAR_MAX_OPACITY * intensity(cx)).toFixed(3);
    if (o < 0.004) continue;
    out.push(`<rect x="${x}" y="0" width="${BAR_WIDTH}" height="${H}" fill="url(#bar)" opacity="${o}"/>`);
  }
  return out.join('\n    ');
}

// Mark and wordmark are placed separately (not as the lockup file's
// proportions): mark MARK_HEIGHT tall, wordmark ink WORDMARK_INK_HEIGHT,
// GAP apart, the pair centred in the frame. `wordPath` is the wordmark's
// <path> from the lockup SVG and `wordBox` its ink box in that SVG's units
// (measured by renderOg); `markSvg` is final/abstractly-mark-white.svg.
export function buildSvg(markSvg, wordPath, wordBox) {
  const vb = markSvg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const markInner = markSvg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const ms = MARK_HEIGHT / vb[3];
  const markW = vb[2] * ms;
  const ws = WORDMARK_INK_HEIGHT / wordBox.height;
  const wordW = wordBox.width * ws;
  const left = W / 2 - (markW + GAP + wordW) / 2;
  // Vertical: word ink centre wc, mark centre wc - MARK_RAISE; centre the union.
  const wc = H / 2 + MARK_RAISE / 2;
  const markTop = wc - MARK_RAISE - MARK_HEIGHT / 2;
  const wordTop = wc - WORDMARK_INK_HEIGHT / 2;
  const mx = left - vb[0] * ms, my = markTop - vb[1] * ms;
  const wx = left + markW + GAP - wordBox.x * ws, wy = wordTop - wordBox.y * ws;
  const f = (n) => n.toFixed(3);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- Generated by design/logo/og/build_og.mjs; edit that, not this. -->
  <defs>
    <!-- Each bar: gold, brightest mid-height, fading to black top and bottom. -->
    <linearGradient id="bar" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#b68a4e" stop-opacity="0"/>
      <stop offset="0.28" stop-color="#d9b273" stop-opacity="0.9"/>
      <stop offset="0.5" stop-color="#f6dca8" stop-opacity="1"/>
      <stop offset="0.72" stop-color="#d9b273" stop-opacity="0.9"/>
      <stop offset="1" stop-color="#b68a4e" stop-opacity="0"/>
    </linearGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="${BG}"/>
  <g shape-rendering="crispEdges">
    ${bars()}
  </g>
  <g transform="translate(${f(mx)} ${f(my)}) scale(${f(ms)})">${markInner}</g>
  <g transform="translate(${f(wx)} ${f(wy)}) scale(${ws.toFixed(5)})">${wordPath}</g>
</svg>
`;
}

export async function renderOg(browser, here, frontend) {
  const lockupSvg = fs.readFileSync(path.join(here, 'final', 'abstractly-lockup-white.svg'), 'utf8');
  const markSvg = fs.readFileSync(path.join(here, 'final', 'abstractly-mark-white.svg'), 'utf8');
  const wordPath = (lockupSvg.match(/<path[\s\S]*?\/>/) || [])[0];
  if (!wordPath) throw new Error('No wordmark <path> in final/abstractly-lockup-white.svg');

  // Measure the lockup in a real layout engine.
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  await page.setContent(`<html><body style="margin:0">${lockupSvg}</body></html>`);
  // Screen rects include every transform (the wordmark path carries its
  // own); convert them back to the lockup's viewBox units.
  const { wordBox } = await page.evaluate(() => {
    const svg = document.querySelector('svg');
    svg.style.width = '1000px';
    svg.style.height = 'auto';
    const vb = svg.viewBox.baseVal;
    const r = svg.getBoundingClientRect();
    const k = vb.width / r.width;
    const toUnits = (b) => ({ x: (b.left - r.left) * k + vb.x, y: (b.top - r.top) * k + vb.y,
                              width: b.width * k, height: b.height * k });
    return { wordBox: toUnits(svg.querySelector('path').getBoundingClientRect()) };
  });
  await page.close();

  const svg = buildSvg(markSvg, wordPath, wordBox);
  const svgOut = path.join(here, 'og', 'og-image.svg');
  fs.writeFileSync(svgOut, svg);

  const shot = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: SCALE });
  await shot.setContent(`<html><body style="margin:0;background:${BG}">${svg}</body></html>`);
  const png = await shot.screenshot({ clip: { x: 0, y: 0, width: W, height: H } });
  await shot.close();
  fs.writeFileSync(path.join(frontend, 'og-image.png'), png);
  return { svgOut, wordBox, scale: WORDMARK_INK_HEIGHT / wordBox.height };
}
